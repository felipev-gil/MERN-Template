const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const request = require('supertest');
const bcrypt = require('bcryptjs');
const db = require('../src/config/database');
const users = require('../src/models/userModel');
const { createApp } = require('../src/app');
const uri = process.env.TEST_MONGO_URI;
const databaseName = value => value?.split('?')[0].split('/').at(-1);
if (!uri || !/^[\w-]+_test$/.test(databaseName(uri)) || databaseName(uri) === databaseName(process.env.MONGO_URI)) throw new Error('Set TEST_MONGO_URI to a separate database ending in _test.');
const prefix = 'integration_' + randomUUID().replaceAll('-', '');
const config = { mode: 'test', clientOrigin: 'http://localhost:5173', jwtSecret: randomUUID() + randomUUID(), rateLimitEnabled: false };
const app = createApp(config);
const post = (path, data) => request(app).post('/api/auth/' + path).set('Origin', config.clientOrigin).send(data);
before(() => db.connectDatabase(uri));
after(async () => { try { await users.User.deleteMany({ email: { $regex: '^' + prefix } }); } finally { await db.closeDatabase(); } });
test('real MongoDB hashing, unique index, login, readiness and session revocation', async () => {
  const fields = { name: 'Integration User', email: prefix + '@example.test', password: 'integration-password' };
  const concurrent = await Promise.all([post('register', fields), post('register', fields)]);
  assert.deepEqual(concurrent.map(r => r.status).sort(), [201, 409]);
  const stored = await users.findByEmail(fields.email);
  assert.equal(await bcrypt.compare(fields.password, stored.passwordHash), true);
  const login = await post('login', fields);
  assert.equal(login.status, 200);
  const cookie = login.headers['set-cookie'][0].split(';')[0];
  await request(app).get('/api/auth/me').set('Cookie', cookie).expect(200);
  await request(app).get('/api/ready').expect(200);
  await request(app).post('/api/auth/logout').set('Origin', config.clientOrigin).set('Cookie', cookie).expect(204);
  await request(app).get('/api/auth/me').set('Cookie', cookie).expect(401);
});
